/**
 * Prints a Markdown inventory of every HTTP route with its auth requirement, read from the real decorators.
 * Usage: DATABASE_URL=... (+ required env) npx ts-node scripts/routes.ts > ../../docs/API_ROUTES.md
 */
import 'reflect-metadata';
import { DiscoveryService, Reflector } from '@nestjs/core';
import { METHOD_METADATA, PATH_METADATA } from '@nestjs/common/constants';
import { RequestMethod } from '@nestjs/common';
import { createApp } from '../src/bootstrap';
import { IS_PUBLIC, ROLES_KEY } from '../src/common/auth';

const METHODS = ['GET', 'POST', 'PUT', 'DELETE', 'PATCH', 'ALL', 'OPTIONS', 'HEAD'];
const join = (...p: (string | string[] | undefined)[]) => '/' + p.flat().filter(Boolean).join('/').replace(/\/+/g, '/').replace(/^\/|\/$/g, '');

async function main() {
  const app = await createApp();
  await app.init();
  const discovery = app.get(DiscoveryService);
  const reflector = app.get(Reflector);
  const rows: { tag: string; method: string; path: string; access: string }[] = [];

  for (const w of discovery.getControllers()) {
    const { instance, metatype } = w;
    if (!instance || !metatype) continue;
    const prefix = Reflect.getMetadata(PATH_METADATA, metatype);
    const proto = Object.getPrototypeOf(instance);
    for (const name of Object.getOwnPropertyNames(proto)) {
      const handler = proto[name];
      if (name === 'constructor' || typeof handler !== 'function') continue;
      const method = Reflect.getMetadata(METHOD_METADATA, handler);
      if (method === undefined) continue;
      const path = Reflect.getMetadata(PATH_METADATA, handler);
      const isPublic = reflector.getAllAndOverride<boolean>(IS_PUBLIC, [handler, metatype]);
      const roles = reflector.getAllAndOverride<string[]>(ROLES_KEY, [handler, metatype]);
      rows.push({
        tag: metatype.name.replace('Controller', ''),
        method: METHODS[method as RequestMethod],
        path: join(prefix, path),
        access: isPublic ? 'public' : roles?.length ? `roles: ${roles.join(', ')}` : 'any authenticated user',
      });
    }
  }
  rows.sort((a, b) => a.tag.localeCompare(b.tag) || a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
  const out: string[] = ['# API route inventory', '', '_Generated by `apps/api/scripts/routes.ts` from the actual decorators — regenerate instead of editing._', ''];
  let cur = '';
  for (const r of rows) {
    if (r.tag !== cur) {
      cur = r.tag;
      out.push('', `## ${cur}`, '', '| Method | Path | Access |', '|---|---|---|');
    }
    out.push(`| ${r.method} | \`${r.path}\` | ${r.access} |`);
  }
  out.push('', `Total: ${rows.length} routes.`);
  console.log(out.join('\n'));
  await app.close();
}
main().catch((e) => { console.error(e); process.exit(1); });
